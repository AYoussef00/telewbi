-- -------------------------------------------------------------------------
-- 1) جدول إعدادات عامة بسيط (Key/Value) — أول استخدام له: التحكم بإظهار/
--    إخفاء خيار "إنشاء حساب" بشاشة دخول الموظفين من لوحة الإدارة، وقابل
--    لإعادة الاستخدام لأي إعداد عام آخر مستقبلاً بنفس الفكرة.
-- -------------------------------------------------------------------------
create table if not exists public.app_settings (
    key text primary key,
    value jsonb not null,
    updated_at timestamptz not null default now(),
    updated_by uuid references public.users(id)
);

insert into public.app_settings (key, value)
values ('employee_self_registration_enabled', 'true'::jsonb)
on conflict (key) do nothing;

alter table public.app_settings enable row level security;

drop policy if exists "app_settings_public_read" on public.app_settings;
create policy "app_settings_public_read"
on public.app_settings for select
to anon, authenticated
using (true);

drop policy if exists "app_settings_admin_write" on public.app_settings;
create policy "app_settings_admin_write"
on public.app_settings for all
to authenticated
using (exists (select 1 from public.users u where u.id = auth.uid() and u.role in ('super_admin', 'admin')))
with check (exists (select 1 from public.users u where u.id = auth.uid() and u.role in ('super_admin', 'admin')));


-- -------------------------------------------------------------------------
-- 2) جدول طلبات تسجيل الموظفين الذاتي (تحت المراجعة)
-- -------------------------------------------------------------------------
create table if not exists public.employee_signup_requests (
    id bigint generated by default as identity primary key,
    user_id uuid not null unique references auth.users(id) on delete cascade,
    employee_id integer references public.employees(id) on delete set null,
    name text not null,
    national_id text not null,
    mobile_number text,
    email text not null,
    company_id integer references public.companies(id),
    job_title text,
    join_date date,
    contract_url text,
    id_photo_url text,
    national_address_url text,
    iban_certificate_url text,
    cv_url text,
    status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
    rejection_reason text,
    reviewed_by uuid references public.users(id),
    reviewed_at timestamptz,
    created_at timestamptz not null default now()
);

-- منع أكثر من طلب معلّق واحد بنفس رقم الهوية أو نفس البريد في آنٍ واحد
-- (لا يمنع إعادة التقديم لاحقاً برقم هوية سبق رفض طلبه، لأن هذا الفهرس
-- الجزئي يشمل فقط الصفوف بحالة 'pending')
create unique index if not exists employee_signup_requests_pending_national_id_idx
    on public.employee_signup_requests (national_id) where (status = 'pending');
create unique index if not exists employee_signup_requests_pending_email_idx
    on public.employee_signup_requests (email) where (status = 'pending');

alter table public.employee_signup_requests enable row level security;

-- الموظف صاحب الطلب: يُضيف طلبه الخاص فقط (بعد إنشاء حساب Auth الخاص به)
drop policy if exists "signup_requests_self_insert" on public.employee_signup_requests;
create policy "signup_requests_self_insert"
on public.employee_signup_requests for insert
to authenticated
with check (auth.uid() = user_id);

drop policy if exists "signup_requests_self_select" on public.employee_signup_requests;
create policy "signup_requests_self_select"
on public.employee_signup_requests for select
to authenticated
using (auth.uid() = user_id);

-- الإدارة (مسؤول / مدير عام النظام): ترى كل الطلبات وتراجعها (موافقة/رفض)
drop policy if exists "signup_requests_admin_select" on public.employee_signup_requests;
create policy "signup_requests_admin_select"
on public.employee_signup_requests for select
to authenticated
using (exists (select 1 from public.users u where u.id = auth.uid() and u.role in ('super_admin', 'admin')));

drop policy if exists "signup_requests_admin_update" on public.employee_signup_requests;
create policy "signup_requests_admin_update"
on public.employee_signup_requests for update
to authenticated
using (exists (select 1 from public.users u where u.id = auth.uid() and u.role in ('super_admin', 'admin')))
with check (exists (select 1 from public.users u where u.id = auth.uid() and u.role in ('super_admin', 'admin')));


-- -------------------------------------------------------------------------
-- 3) صلاحية إضافية آمنة على جدول employees: تسمح لأي مستخدم موثّق (Authenticated)
--    بإدراج صفّه الخاص هو فقط (user_id = uid()) وبحالة "inactive" حصراً فقط —
--    صلاحية إضافية جديدة تُضاف بجانب صلاحيات لوحة تحكم الإدارة الحالية دون
--    أي تأثير عليها (سياسات RLS المتعددة على نفس الجدول تُجمع بمنطق "أو").
-- -------------------------------------------------------------------------
drop policy if exists "employees_self_signup_insert" on public.employees;
create policy "employees_self_signup_insert"
on public.employees for insert
to authenticated
with check (auth.uid() = user_id and status = 'inactive');


-- -------------------------------------------------------------------------
-- 4) دوال RPC آمنة (SECURITY DEFINER) تُستخدَم من شاشة التسجيل العامة (قبل
--    تسجيل الدخول) للبحث عن الشركات/المسميات الوظيفية، دون فتح صلاحية قراءة
--    عامة على كامل بيانات جدولي companies/professions الحسّاسة (بيانات
--    الشركات تشمل أرقاماً ضريبية وهواتف وقيم اشتراكات... إلخ لا يصح كشفها
--    لزائر غير مسجّل دخول؛ هذه الدوال تُعيد فقط المعرّف والاسم).
-- -------------------------------------------------------------------------
create or replace function public.search_companies_for_signup(p_query text default '')
returns table (id integer, name text)
language sql
security definer
set search_path = public
as $$
    select c.id, c.name
    from public.companies c
    where (p_query = '' or c.name ilike '%' || p_query || '%')
    order by c.name asc
    limit 500;
$$;
grant execute on function public.search_companies_for_signup(text) to anon, authenticated;

create or replace function public.search_professions_for_signup(p_query text default '')
returns table (id uuid, name_ar text, name_en text)
language sql
security definer
set search_path = public
as $$
    select p.id, p.name_ar, p.name_en
    from public.professions p
    where (p_query = '' or p.name_ar ilike '%' || p_query || '%' or p.name_en ilike '%' || p_query || '%')
    order by p.name_ar asc
    limit 500;
$$;
grant execute on function public.search_professions_for_signup(text) to anon, authenticated;

-- فحص أهلية التسجيل (تكرار رقم الهوية + القائمة السوداء) — تُستدعى قبل إنشاء
-- الحساب لإعطاء رسالة مبكرة وواضحة للمستخدم دون كشف أي بيانات حسّاسة أخرى
create or replace function public.check_employee_signup_eligibility(p_national_id text)
returns jsonb
language sql
security definer
set search_path = public
as $$
    select jsonb_build_object(
        'is_duplicate',
            exists(select 1 from public.employees e where e.national_id = p_national_id)
            or exists(
                select 1 from public.employee_signup_requests r
                where r.national_id = p_national_id and r.status in ('pending', 'approved')
            ),
        'is_blacklisted', exists(select 1 from public.employee_blacklist b where b.national_id = p_national_id),
        'blacklist_reason', (select b.reason from public.employee_blacklist b where b.national_id = p_national_id limit 1)
    );
$$;
grant execute on function public.check_employee_signup_eligibility(text) to anon, authenticated;


-- -------------------------------------------------------------------------
-- 5) تخزين المرفقات (السيرة الذاتية / الهوية / العنوان الوطني / شهادة
--    الآيبان / العقد): إعادة استخدام نفس الـ bucket المستخدم أصلاً من شاشة
--    "إضافة موظف" الإدارية (employee-documents)، مع التأكد من وجوده وصلاحية
--    الرفع لأي مستخدم موثّق (يشمل موظفاً جديداً أنشأ حسابه للتو ذاتياً).
-- -------------------------------------------------------------------------
insert into storage.buckets (id, name, public)
values ('employee-documents', 'employee-documents', true)
on conflict (id) do nothing;

drop policy if exists "employee_documents_authenticated_insert" on storage.objects;
create policy "employee_documents_authenticated_insert"
on storage.objects for insert
to authenticated
with check (bucket_id = 'employee-documents');


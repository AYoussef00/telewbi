-- =============================================================================
-- ميزة "أنواع التحصيل" (طرق التحصيل: كاش - بنك - أو أي طريقة أخرى يضيفها
-- المستخدم من شاشة الإعدادات الجديدة)، مع ربطها بسجل تحصيل الموظفين
-- =============================================================================
-- التغييرات:
--   1) جدول جديد collection_types: قائمة طرق التحصيل القابلة للإدارة (إضافة/
--      تعديل الاسم/تفعيل أو إيقاف/حذف) من شاشة "أنواع التحصيل" الجديدة.
--      الطرق "النشطة" فقط هي التي تظهر كخيار عند تعليم تحصيل موظف كمدفوع في
--      شاشة "تحصيل الموظفين"؛ "الموقَفة" تبقى محفوظة (للسجلات القديمة التي
--      استخدمتها) لكنها لا تظهر كخيار جديد بعد الآن.
--   2) عمود جديد على جدول employee_collections: collection_type_id (مرجع
--      لجدول collection_types) — يُسجَّل طريقة التحصيل المُختارة عند تعليم
--      تحصيل الموظف كمدفوع.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1) جدول أنواع/طرق التحصيل
-- -----------------------------------------------------------------------------
create table if not exists public.collection_types (
    id bigint generated by default as identity primary key,
    name text not null,
    status text not null default 'active' check (status in ('active', 'inactive')),
    created_at timestamptz not null default now()
);

-- منع تكرار نفس اسم طريقة التحصيل (بغض النظر عن حالة الأحرف)
create unique index if not exists collection_types_name_unique_idx
    on public.collection_types (lower(name));

alter table public.collection_types enable row level security;

drop policy if exists "collection_types_authenticated_full_access" on public.collection_types;
create policy "collection_types_authenticated_full_access"
    on public.collection_types for all
    to authenticated
    using (true) with check (true);

-- طريقتان افتراضيتان شائعتا الاستخدام (كاش/بنك) — يمكن للمستخدم إضافة المزيد
-- أو إيقافهما لاحقاً من شاشة "أنواع التحصيل"؛ لا تُدرجان مجدداً إن كانتا موجودتين
insert into public.collection_types (name, status)
select v.name, 'active' from (values ('كاش'), ('بنك')) as v(name)
where not exists (
    select 1 from public.collection_types ct where lower(ct.name) = lower(v.name)
);

-- -----------------------------------------------------------------------------
-- 2) عمود طريقة التحصيل على جدول سجل تحصيل الموظفين
-- -----------------------------------------------------------------------------
alter table public.employee_collections
    add column if not exists collection_type_id bigint references public.collection_types(id) on delete set null;


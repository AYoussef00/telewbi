-- =============================================================================
-- ميزة "الرواتب": استيراد رواتب الموظفين الشهرية من ملف Excel (قائمة "الرواتب"
-- ← استيراد/تصدير)، وعرضها كعمود "الرصيد" بشاشة "تحصيل الموظفين" وتقريرها.
-- =============================================================================
-- جدول employee_salaries: راتب مستورد لكل (ربط موظف × شهر). لو لم يُستورد راتب
-- لشهر ما، يُعرض "الرصيد" = الراتب الأساسي المسجَّل بالربط (employee_links
-- .basic_salary_value) تلقائياً — فلا حاجة لأي صف هنا لذلك الشهر.
-- =============================================================================
create table if not exists public.employee_salaries (
    id bigint generated by default as identity primary key,
    employee_link_id integer not null references public.employee_links(id) on delete cascade,
    salary_month date not null,                 -- أول يوم من الشهر، مثال: 2026-11-01
    salary_amount numeric(12,2) not null default 0,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (employee_link_id, salary_month)
);

create index if not exists employee_salaries_month_idx
    on public.employee_salaries (salary_month);

alter table public.employee_salaries enable row level security;

drop policy if exists "employee_salaries_authenticated_full_access" on public.employee_salaries;
create policy "employee_salaries_authenticated_full_access"
    on public.employee_salaries for all
    to authenticated
    using (true) with check (true);

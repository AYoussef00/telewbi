// 🛡️ تهريب HTML المركزي (منع حقن الأكواد XSS)
//
// أي نص يكتبه مستخدم (اسم موظف/شركة، عنوان مهمة، ملاحظة، سبب...) ثم يُدرَج داخل
// قالب HTML (innerHTML) يجب أن يمر بالدالة escHtml، وإلا استطاع شخص كتابة
// <img onerror=...> أو "><script> بحقل عادي فيُنفَّذ كوده بمتصفح المسؤول عند فتح الشاشة
// (فيسرق جلسته). تهرّب هذه الدالة: & < > " ' ` — فتصلح للنص وللسمات (title="...") معاً.
//
// الاستخدام:   `<td>${escHtml(row.name)}</td>`   و   `<a title="${escHtml(row.title)}">`
// لا تُمرِّر إليها HTML جاهزاً تريد عرضه كما هو (أزرار/شارات) — تلك تُبنى من ثوابت فقط.
// =========================================================================
function escHtml(value) {
    if (value === null || value === undefined) return '';
    return String(value)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;')
        .replace(/`/g, '&#96;');
}
